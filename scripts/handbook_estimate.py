"""Problem 2: count the handbook's tokens and estimate what it costs per call.

Writes output/handbook_estimate.md. Re-run any time:  .venv/bin/python scripts/handbook_estimate.py
"""
import json
import re
import statistics as st
from pathlib import Path

import tiktoken
from bs4 import BeautifulSoup
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "output" / "handbook_estimate.md"
MODEL = "gpt-6-luna"

handbook = (DATA / "shop_handbook.md").read_text()
prices = json.loads((DATA / "prices.json").read_text())[MODEL]
P_IN, P_CACHED, P_WRITE, P_OUT = (prices[k] / 1_000_000 for k in
                                  ("input_per_1m", "cached_input_per_1m", "cache_write_per_1m", "output_per_1m"))

o200k = tiktoken.get_encoding("o200k_base")   # GPT-4o / GPT-5-family tokenizer
cl100k = tiktoken.get_encoding("cl100k_base")  # older GPT-4 tokenizer, for comparison
ntok = lambda s: len(o200k.encode(s))

N = ntok(handbook)
chars, words, lines = len(handbook), len(handbook.split()), handbook.count("\n") + 1


def usd(x: float, d: int = 6) -> str:
    return f"${x:,.{d}f}"


# ---- per-section breakdown -------------------------------------------------
parts = re.split(r"(?m)^(?=## )", handbook)
sections = [(p.splitlines()[0].lstrip("# ").strip(), ntok(p), len(p)) for p in parts if p.strip()]
sec_toks = [t for _, t, _ in sections]

# ---- vendor documents, for scale -------------------------------------------
def doc_text(p: Path) -> str:
    if p.suffix == ".pdf":
        return "\n".join(pg.extract_text() or "" for pg in PdfReader(p).pages)
    return p.read_text(errors="ignore")

docs = {}
for folder in ("practice_docs", "exam_docs"):
    docs[folder] = [ntok(doc_text(p)) for p in sorted((DATA / folder).iterdir()) if p.is_file()]
all_docs = docs["practice_docs"] + docs["exam_docs"]


def describe(xs):
    return (len(xs), sum(xs), st.mean(xs), st.median(xs), min(xs), max(xs), st.pstdev(xs))


# ---- cost scenarios --------------------------------------------------------
one_nocache = N * P_IN
one_write = N * P_WRITE
one_read = N * P_CACHED
calls = [1, 10, 100, 1_000, 10_000, 100_000]
best_cached = lambda n: one_write + (n - 1) * one_read          # one cache write, then all reads
# Realistic: 1K calls spread over an 8-hour day with a 30-minute cache TTL -> one write per window.
windows = 16
spread_1k = windows * one_write + (1_000 - windows) * one_read

L = []
w = L.append
w("# Problem 2: Sizing up the Shop Handbook\n")
w(f"The vendor desk agent sends `data/shop_handbook.md` to **{MODEL}** on every call, so it sets the floor "
  "on what each call costs. These are estimates; Problem 4 checks them against the `usage` numbers that real runs report.\n")
w("Generated by `scripts/handbook_estimate.py` (re-run it to reproduce every number here).\n")

w("## 1. Token count\n")
w(f"**The handbook is {N:,} tokens.**\n")
w("**How we got it:** we ran the whole file through OpenAI's open-source tokenizer library "
  "[`tiktoken`](https://github.com/openai/tiktoken) with the `o200k_base` encoding, the one the GPT-4o and "
  "GPT-5-family models use, and counted the tokens:\n")
w("```python\nimport tiktoken\nenc = tiktoken.get_encoding(\"o200k_base\")\n"
  "len(enc.encode(open(\"data/shop_handbook.md\").read()))   # -> " + f"{N:,}\n```\n")
w(f"OpenAI hasn't published {MODEL}'s exact tokenizer, so we treat this as a close estimate. The API also "
  "adds a handful of tokens of message framing per call. Problem 4 replaces the estimate with the `input_tokens` the API reports.\n")
w("### Cross-checks\n")
w("| Method | Estimate | Difference vs o200k |\n|---|---:|---:|")
for name, val in [("tiktoken `o200k_base` (used)", N),
                  ("tiktoken `cl100k_base` (older GPT-4)", len(cl100k.encode(handbook))),
                  ("Rule of thumb: characters ÷ 4", round(chars / 4)),
                  ("Rule of thumb: words × 4/3", round(words * 4 / 3))]:
    w(f"| {name} | {val:,} | {(val - N) / N:+.1%} |")
w("")
w("The two real tokenizers agree within about 1%, so the handbook is about 10K tokens. The usual rules of thumb undercount it by 19 to 28%, "
  "because the handbook is full of tables, SKU codes, and dollar figures, which split into more tokens than plain prose "
  f"({chars / N:.2f} characters per token here, against about 4 for ordinary English). For pricing, count with a tokenizer and don't guess.\n")

w("### Size of the file\n")
w("| Statistic | Value |\n|---|---:|")
for k, v in [("Characters", f"{chars:,}"), ("Words", f"{words:,}"), ("Lines", f"{lines:,}"),
             ("Sections (## headings)", len(sections)), ("Tokens (o200k)", f"{N:,}"),
             ("Characters per token", f"{chars / N:.2f}"), ("Tokens per word", f"{N / words:.2f}")]:
    w(f"| {k} | {v} |")
w("")

w("### Tokens by section\n")
w("| Section | Tokens | Share | Cost per call, uncached |\n|---|---:|---:|---:|")
for name, t, _ in sections:
    w(f"| {name} | {t:,} | {t / N:.1%} | {usd(t * P_IN, 7)} |")
w(f"| **Total** | **{sum(sec_toks):,}** | | **{usd(sum(sec_toks) * P_IN, 7)}** |\n")
big = max(sections, key=lambda s: s[1])
w(f"Counted one at a time, the sections add up to {sum(sec_toks):,} tokens, against {N:,} for the whole file. "
  f"**{big[0]}** is by far the largest at {big[1] / N:.0%} of the file. The two sections the buy/don't-buy rules actually need, "
  "4 (purchasing rules) and 5 to 6 (vendor lists), are a small fraction. That's a lever for trimming the prompt later.\n")
n, s, m, md, lo, hi, sd = describe(sec_toks)
w("| Per-section statistic | Tokens |\n|---|---:|")
for k, v in [("Count", n), ("Mean", f"{m:,.0f}"), ("Median", f"{md:,.0f}"), ("Min", f"{lo:,}"),
             ("Max", f"{hi:,}"), ("Std. dev.", f"{sd:,.0f}")]:
    w(f"| {k} | {v} |")
w("")

w("### The handbook next to the vendor documents\n")
w("Each call sends the handbook **plus** one vendor document. Raw tokens per document (HTML/email source as-is, PDF text extracted with `pypdf`):\n")
w("| Set | Docs | Total tokens | Mean | Median | Min | Max | Std. dev. | Handbook ÷ mean doc |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|")
for label, xs in [("Practice", docs["practice_docs"]), ("Exam", docs["exam_docs"]), ("All", all_docs)]:
    n, s, m, md, lo, hi, sd = describe(xs)
    w(f"| {label} | {n} | {s:,} | {m:,.0f} | {md:,.0f} | {lo:,} | {hi:,} | {sd:,.0f} | {N / m:,.0f}× |")
share = N / (N + st.mean(all_docs))
w(f"\nThe handbook is about **{share:.0%} of the input on a typical call**. The documents themselves are a rounding error, so caching the handbook is where the money is.\n")

w(f"## 2. Prices ({MODEL}, from `data/prices.json`)\n")
w("| Token type | $ per 1M tokens | $ per token | Multiple of normal input |\n|---|---:|---:|---:|")
for k, p in [("Input (uncached)", P_IN), ("Cache write (first time the prefix is stored)", P_WRITE),
             ("Cached input (cache read)", P_CACHED), ("Output", P_OUT)]:
    w(f"| {k} | {p * 1e6:.3f} | {p:.3e} | {p / P_IN:.2f}× |")
w("")

w("## 3. What the handbook alone costs\n")
w(f"Input tokens only, for N = {N:,} handbook tokens. Output, the vendor document, and the system-prompt wording are left out on purpose; this is the fixed cost the handbook adds to every call.\n")
w("### One call\n")
w("| Case | Math | Cost |\n|---|---|---:|")
w(f"| Without caching | {N:,} × $0.10 / 1,000,000 | **{usd(one_nocache, 7)}** |")
w(f"| With caching, first call (cache write) | {N:,} × $0.125 / 1,000,000 | **{usd(one_write, 7)}** |")
w(f"| With caching, later call (cache read) | {N:,} × $0.01 / 1,000,000 | **{usd(one_read, 7)}** |")
w("")
w(f"A single call is about a tenth of a cent. The first cached call costs **25% more** than an uncached one (it pays to store the prefix). "
  f"Every call after that is **90% cheaper**.\n")

w("### 1,000 calls\n")
w("| Case | Math | Cost | vs no cache |\n|---|---|---:|---:|")
c1k_nc = 1_000 * one_nocache
c1k_best = best_cached(1_000)
w(f"| Without caching | 1,000 × {N:,} × $0.10/1M | **{usd(c1k_nc, 4)}** | — |")
w(f"| With caching, best case (1 write + 999 reads, all within the cache's lifetime) | "
  f"{usd(one_write, 7)} + 999 × {usd(one_read, 7)} | **{usd(c1k_best, 4)}** | {c1k_best / c1k_nc - 1:+.1%} |")
w(f"| With caching, spread over an 8-hour day (30-min TTL → {windows} writes + {1_000 - windows} reads) | "
  f"{windows} × {usd(one_write, 7)} + {1_000 - windows} × {usd(one_read, 7)} | **{usd(spread_1k, 4)}** | {spread_1k / c1k_nc - 1:+.1%} |")
w(f"| With caching, worst case (the cache always expires before the next call → 1,000 writes) | "
  f"1,000 × {usd(one_write, 7)} | **{usd(1_000 * one_write, 4)}** | {P_WRITE / P_IN - 1:+.1%} |")
w("")
w(f"Caching cuts the handbook bill for 1K calls from about **$1.01 to about $0.10**, a {1 - c1k_best / c1k_nc:.0%} saving, "
  "as long as the calls come close enough together to reuse the cache. If calls are hours apart, every call pays the write premium and caching costs more than not caching.\n")

w("### Scaling up\n")
w("| Calls | No cache | Cached (best case) | Saved | Saving |\n|---:|---:|---:|---:|---:|")
for c in calls:
    a, b = c * one_nocache, best_cached(c)
    w(f"| {c:,} | {usd(a, 4)} | {usd(b, 4)} | {('−' if a < b else '') + usd(abs(a - b), 4)} | {1 - b / a:.1%} |")
w("")
w(f"Break-even: caching wins once a cache write is reused at least once. Two calls cost {usd(2 * one_nocache, 7)} uncached and "
  f"{usd(one_write + one_read, 7)} cached. With many calls the per-call cost approaches the cache-read price, "
  f"{usd(one_read, 7)}, which is 10% of the uncached cost.\n")

w("## 4. Assumptions to check in Problem 4\n")
w(f"1. **Token count.** Real `input_tokens` should be about {N:,} plus the system prompt, the vendor document, and message framing. "
  f"The API, not tiktoken, has the final word on {MODEL}.")
w("2. **Cache hits.** On the second and later calls, `input_tokens_details.cached_tokens` should be close to the handbook size, provided the handbook sits "
  "**first** in the prompt, unchanged byte-for-byte, with a `prompt_cache_breakpoint` right after it (Lecture 11). Providers may cache in fixed-size blocks, "
  "so a few dozen tokens at the end may still bill as normal input.")
w("3. **Cache write.** The first call should show about the same number in `cache_write_tokens`, billed at $0.125/1M.")
w("4. **Billing math.** `input_tokens` already includes the cached and cache-write tokens, so "
  "the uncached part = input − cached − cache_write, billed at $0.10/1M.")

OUT.write_text("\n".join(L) + "\n")
print(f"wrote {OUT.relative_to(ROOT)}  |  handbook = {N:,} tokens  |  1 call ${one_nocache:.6f} | 1K calls ${c1k_nc:.4f} vs ${c1k_best:.4f} cached")
